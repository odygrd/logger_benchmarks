#!/usr/bin/env python3
"""
Generates the log statements of the many statements throughput benchmarks, into
benchmarks/backend_total_time/many_statements/.

The other throughput benchmarks cycle between five log statements, so the backend keeps seeing
the same few format strings, argument types and call sites. An application has hundreds of
statements, logged in no fixed order. These benchmarks log NUM_STATEMENTS distinct statements of
one to five mixed arguments, in the pseudo-random order of bench_statement_order (see
many_statements.h).

Every library writes the same messages. Libraries take their arguments in different ways, so one
file is generated per call style:

- fmt.inc: BENCH_LOG("text {}", args...), for libraries with {fmt} style format strings
- printf.inc: BENCH_LOG("text %lu", args...), with C conversions, for PlatformLab NanoLog
- reckless.inc: BENCH_LOG("text %d", args...), with the conversions Reckless accepts
- stream.inc: BENCH_LOG_STREAM(<< "text " << arg ...), for stream style libraries

Each file is the body of the log_statement(iteration) lambda of a benchmark. Run this script again
after changing it; the generated files are committed.
"""

from __future__ import annotations

import random
from pathlib import Path

OUTPUT_DIR = Path(__file__).resolve().parents[1] / "benchmarks" / "backend_total_time" / "many_statements"
RNG_SEED = 1337
NUM_STATEMENTS = 256

WORDS = ["order", "quantity", "price", "venue", "side", "sequence", "latency", "bytes", "session",
         "symbol", "fill", "cancel", "retry", "depth", "spread", "bid", "ask", "position", "risk",
         "limit", "book", "level", "message", "connection", "gap", "count", "worker", "request"]
PREFIXES = ["", "Event ", "Order update ", "Risk check ", "Market data ", "Session "]
SEPARATORS = [" ", ", ", " | "]

# The argument types an application commonly logs, all derived from the iteration:
# (expression, C conversion, Reckless conversion)
ARGUMENTS = [
    ("iteration", "%lu", "%d"),
    ("-static_cast<int64_t>(iteration)", "%ld", "%d"),
    ("static_cast<double>(iteration) / 8", "%f", "%f"),
    ("bench_symbols[iteration & 7]", "%s", "%s"),
    ("static_cast<char>('A' + iteration % 26)", "%c", "%s"),
    ("static_cast<uint32_t>(iteration * 3)", "%u", "%d"),
]


def generate_statements() -> list[tuple[list[str], list[tuple[str, str, str]]]]:
    """
    Each statement as its text pieces around the arguments, and its arguments
    """
    rng = random.Random(RNG_SEED)
    statements = []

    for index in range(NUM_STATEMENTS):
        num_args = rng.randint(1, 5)
        names = [rng.choice(WORDS) for _ in range(num_args)]
        separator = rng.choice(SEPARATORS)
        prefix = f"{rng.choice(PREFIXES)}#{index} "
        args = [rng.choice(ARGUMENTS) for _ in range(num_args)]

        pieces = [f"{prefix}{names[0]}: "]
        for name in names[1:]:
            pieces.append(f"{separator}{name}: ")
        pieces.append("")

        statements.append((pieces, args))

    return statements


def format_call(pieces: list[str], args: list[tuple[str, str, str]], style: str) -> str:
    if style == "stream":
        parts = []
        for piece, arg in zip(pieces, args):
            parts.append(f'"{piece}"')
            parts.append(arg[0])
        return f"BENCH_LOG_STREAM(<< {' << '.join(parts)});"

    conversion = {"fmt": lambda arg: "{}", "printf": lambda arg: arg[1], "reckless": lambda arg: arg[2]}[style]
    text = "".join(piece + (conversion(arg) if i < len(args) else "") for i, (piece, arg) in
                   enumerate(zip(pieces, args + [None])))
    expressions = ", ".join(arg[0] for arg in args)
    return f'BENCH_LOG("{text}", {expressions});'


def write_file(statements, style: str) -> None:
    lines = [
        "// Generated by tools/gen_many_statements.py, do not edit",
        "// clang-format off",
        "switch (bench_statement_order[iteration & (bench_statement_order.size() - 1)])",
        "{",
    ]
    for index, (pieces, args) in enumerate(statements):
        lines.append(f"case {index}:")
        lines.append(f"  {format_call(pieces, args, style)}")
        lines.append("  break;")
    lines += ["default:", "  break;", "}", "// clang-format on", ""]

    (OUTPUT_DIR / f"{style}.inc").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    statements = generate_statements()
    for style in ("fmt", "printf", "reckless", "stream"):
        write_file(statements, style)


if __name__ == "__main__":
    main()
